const englishKeys = Object.keys(translations.en);
for (const { code } of languages) {
  const missingKeys = englishKeys.filter(key => !(key in translations[code]));
  if (missingKeys.length > 0) {
    throw new Error(`Missing ${code} translations: ${missingKeys.join(', ')}.`);
  }
}

let currentLanguage = 'es';
const languageChangeListeners = new Set();

document.documentElement.lang = 'es-AR';

export function translate(key, values = {}) {
  const message = translations[currentLanguage][key];
  if (message === undefined) {
    throw new Error(`Missing translation "${key}" for "${currentLanguage}".`);
  }
  return message.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  const selectedLanguage = languages.find(({ code }) => code === language);
  if (!selectedLanguage) {
    throw new RangeError(`Unsupported language "${language}".`);
  }

  currentLanguage = selectedLanguage.code;
  document.documentElement.lang = selectedLanguage.locale;
  document.documentElement.dir = selectedLanguage.direction ?? 'ltr';
  languageChangeListeners.forEach(listener => listener());
}

export function onLanguageChange(listener) {
  languageChangeListeners.add(listener);
  return () => languageChangeListeners.delete(listener);
}

export function createLanguagePickerButton() {
  const button = document.createElement('button');
  button.id = 'language-toggle';
  button.type = 'button';

  const icon = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  icon.setAttribute('viewBox', '0 0 24 24');
  icon.setAttribute('aria-hidden', 'true');
  icon.setAttribute('focusable', 'false');
  icon.innerHTML = '<circle cx="12" cy="12" r="9"/><path d="M3 12h18M12 3a15 15 0 0 1 0 18M12 3a15 15 0 0 0 0 18"/>';
  const label = document.createElement('span');
  button.append(icon, label);

  const updateButton = () => {
    label.textContent = translate('selectLanguage');
    button.setAttribute('aria-label', translate('selectLanguage'));
    button.title = translate('selectLanguage');
    button.dataset.tooltip = translate('selectLanguage');
  };

  button.addEventListener('click', () => {
    window.dispatchEvent(new Event('cube-language-open'));
  });
  onLanguageChange(updateButton);
  updateButton();
  return button;
}
